"""Render ``lidar_inspection_report.json`` as a Markdown data report (tables only).

Interpretation and recommendations live in ``docs/phase2_lidar_inspection.md``.
"""

from __future__ import annotations

from typing import Any

import numpy as np


def _fmt(v: Any, nd: int = 2) -> str:
    if v is None:
        return "—"
    if isinstance(v, float):
        return f"{v:,.{nd}f}"
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def _band(profile: list[dict[str, Any]], lo: float, hi: float) -> str:
    """Median density of across-track bins whose |offset| lies within [lo, hi] metres."""
    v = [
        p["median_pts_per_m2"]
        for p in profile
        if lo <= min(abs(p["offset_m"][0]), abs(p["offset_m"][1]))
        and max(abs(p["offset_m"][0]), abs(p["offset_m"][1])) <= hi
    ]
    return _fmt(float(np.median(v)), 0) if v else "—"


def render_markdown(result: dict[str, Any]) -> str:
    files = result["files"]
    usable = [f for f in files if f.get("usable")]
    lines: list[str] = [
        "# LiDAR inspection — measured data report",
        "",
        "Generated by `scripts/inspect_lidar.py report` from the real files in "
        "`data/raw/pointclouds/`. All values are measured on decoded, validated points "
        "unless labelled *estimate*. Coordinates are in the files' (undeclared) CRS.",
        "",
        "## 1. Files",
        "",
        "| File | Size MB | Header points | Valid points read | Corrupt / unreadable chunks |"
        " Status |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for f in files:
        hdr = f.get("header") or {}
        lc = f.get("laz_chunks") or {}
        n_c = len(lc.get("corrupt_chunks", []))
        n_u = len(lc.get("unreadable_chunks", []))
        nch = lc.get("n_chunks")
        status = "usable" if f.get("usable") else f"NOT usable: {f.get('error')}"
        if f.get("usable") and (n_c or n_u):
            status = "usable, partially corrupt"
        lines.append(
            f"| {f['file']} | {_fmt((f.get('size_bytes') or 0) / 2**20, 1)} | "
            f"{_fmt(hdr.get('point_count'))} | {_fmt(f.get('streamed_point_count'))} | "
            f"{n_c} / {n_u} of {_fmt(nch)} | {status} |"
        )
    lines += [
        "",
        "## 2. Header metadata (usable files)",
        "",
        "| File | LAS | PF | Scale | Offset (x, y, z) | X range | Y range | Z range | CRS |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for f in usable:
        h = f["header"]
        lines.append(
            f"| {f['file']} | {h['version']} | {h['point_format']} | {h['scales'][0]} | "
            f"{', '.join(_fmt(o, 3) for o in h['offsets'])} | "
            f"{_fmt(f['xyz_min'][0], 1)} … {_fmt(f['xyz_max'][0], 1)} | "
            f"{_fmt(f['xyz_min'][1], 1)} … {_fmt(f['xyz_max'][1], 1)} | "
            f"{_fmt(f['xyz_min'][2], 2)} … {_fmt(f['xyz_max'][2], 2)} | "
            f"{'none' if not h.get('crs_wkt') else 'present'} |"
        )
    lines += [
        "",
        "## 3. Point attributes",
        "",
        "| File | Classes (code: count) | Returns 1/2/3/4 | Single-return % | Point source IDs |"
        " RGB min–max | Scan angle range |",
        "|---|---|---|---:|---|---|---|",
    ]
    for f in usable:
        rm = f["return_matrix"]
        by_rn = [sum(rm[r]) for r in range(1, 5)]
        single = sum(rm[r][1] for r in range(8))
        tot = max(f["streamed_point_count"], 1)
        rgb = f.get("rgb") or {}
        sa = [int(k) for k in f["scan_angle_counts"]]
        lines.append(
            f"| {f['file']} | {', '.join(f'{k}: {_fmt(v)}' for k, v in f['class_counts'].items())}"
            f" | {' / '.join(_fmt(v) for v in by_rn)} | {_fmt(100 * single / tot, 1)} | "
            f"{', '.join(f'{k} ({_fmt(v)})' for k, v in f['point_source_counts'].items())} | "
            f"{rgb.get('min')}–{rgb.get('max')} | {min(sa)}° … {max(sa)}° |"
        )
    lines += [
        "",
        "## 4. Intensity (all valid points)",
        "",
        "| File | Min | p1 | p5 | p50 | p95 | p99 | p99.9 | Max | Zero % | At-max % |"
        " Saturated % |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for f in usable:
        i = f["intensity"]
        p = i["percentiles"]
        lines.append(
            f"| {f['file']} | {i['min']} | {p['p1']} | {p['p5']} | {p['p50']} | {p['p95']} | "
            f"{p['p99']} | {p['p99.9']} | {i['max']} | {_fmt(i['zero_pct'], 3)} | "
            f"{_fmt(i['at_max_pct'], 3)} | {_fmt(i['saturated_pct'], 3)} |"
        )
    lines += [
        "",
        "Road-candidate cells (mean intensity per 1 m cell) and regional variation:",
        "",
        "| File | Road cell p5 | p50 | p95 | 100 m blocks | Block median min–max |" " Max/min |",
        "|---|---:|---:|---:|---:|---|---:|",
    ]
    for f in usable:
        r = f.get("intensity_road_cells") or {}
        g = f.get("intensity_regional_100m_blocks") or {}
        b = g.get("block_median_intensity") or {}
        lines.append(
            f"| {f['file']} | {_fmt(r.get('p5'), 0)} | {_fmt(r.get('p50'), 0)} | "
            f"{_fmt(r.get('p95'), 0)} | {g.get('blocks', 0)} | "
            f"{_fmt(b.get('min'), 0)} – {_fmt(b.get('max'), 0)} | {_fmt(g.get('max_over_min'))} |"
        )
    lines += [
        "",
        "## 5. Point density",
        "",
        "Bounding-box density is shown only for contrast — it is **not** road density.",
        "",
        "| File | BBox pts/m² (not road) | Occupied cells p50 | Road cells p5 | p25 | p50 |"
        " p95 | Road CV | Implied spacing @p50 (m) | Road cells < ½ median % |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for f in usable:
        d = f["density"]
        a = d["all_occupied_cells"]
        r = d["road_candidate_cells"]
        rp = r.get("pts_per_m2", {})
        lines.append(
            f"| {f['file']} | {_fmt(d['bbox_pts_per_m2_NOT_road_density'])} | "
            f"{_fmt(a['pts_per_m2']['p50'])} | {_fmt(rp.get('p5'))} | {_fmt(rp.get('p25'))} | "
            f"{_fmt(rp.get('p50'))} | {_fmt(rp.get('p95'))} | {_fmt(r.get('cv'), 3)} | "
            f"{_fmt(r.get('implied_spacing_m_at_median'), 3)} | "
            f"{_fmt(r.get('cells_below_half_median_pct'))} |"
        )
    lines += [
        "",
        "Nearest-neighbour spacing on road-candidate points, 10 m × 10 m samples "
        "(exact KD-tree, XY):",
        "",
        "| Sample | Road pts | pts/m² | NN p5 | NN p50 | NN p95 | Coincident XY % |"
        " Passes (GPS gaps > 10 s) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for f in usable:
        for s in f.get("density_samples", []):
            nn = s.get("nn_spacing_road") or {}
            q = nn.get("nn_m") or {}
            lines.append(
                f"| {s['window']} | {_fmt(s.get('road_candidate_points'))} | "
                f"{_fmt(s.get('road_density_pts_m2'))} | {_fmt(q.get('p5'), 3)} | "
                f"{_fmt(q.get('p50'), 3)} | {_fmt(q.get('p95'), 3)} | "
                f"{_fmt(nn.get('coincident_xy_pct'), 2)} | "
                f"{_fmt(s.get('road_passes_gps_gap_10s'))} |"
            )
    lines += [
        "",
        "## 6. Road-surface candidate (heuristic estimate)",
        "",
        f"Criteria: `{result['criteria']}`",
        "",
        "| File | Candidate area m² | enough pts % | single-return % | flat % | low-slope % |"
        " in large component % | candidate % | Empty 1 m cells inside road corridor |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for f in usable:
        rs = f["road_surface"]
        c = rs["criteria_pass_pct_of_occupied_cells"]
        lines.append(
            f"| {f['file']} | {_fmt(rs['candidate_area_m2'])} | {c['enough_points']} | "
            f"{c['single_return']} | {c['flat_cell']} | {c['low_slope']} | {c['large_component']} |"
            f" {c['candidate']} | {_fmt(rs['empty_1m_cells_inside_road_corridor'])} |"
        )
    lines += [
        "",
        "## 7. Preview windows — observed coverage per resolution",
        "",
        "No-data % = road pixels with zero points (observed, before any display fill).",
        "",
        "| Window | GSD (cm) | Road pixels | Road no-data % | Pts/pixel p5 | p50 | p95 |"
        " 15 cm marking width (px) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for f in usable:
        for p in f.get("previews", []):
            for gsd, g in (p.get("gsd") or {}).items():
                q = g.get("road_points_per_pixel") or {}
                lines.append(
                    f"| {p['window']} | {float(gsd) * 100:.1f} | {_fmt(g['road_pixels'])} | "
                    f"{_fmt(g['road_nodata_pct'])} | {_fmt(q.get('p5'), 0)} | "
                    f"{_fmt(q.get('p50'), 0)} | {_fmt(q.get('p95'), 0)} | "
                    f"{_fmt(g['marking_width_px'], 1)} |"
                )
    lines += [
        "",
        "## 8. Acquisition geometry (estimates)",
        "",
        "| File | Corridor length m | Swath width p5/p50/p95 m | GPS duration s | Speed m/s |"
        " Point rate pts/s | Density on axis (±10 m) | Density at 40–50 m |",
        "|---|---:|---|---:|---:|---:|---:|---:|",
    ]
    for f in usable:
        a = f.get("acquisition") or {}
        prof = a.get("across_track_density") or []
        sw = a.get("swath_width_m_p5_p50_p95") or [None] * 3
        lines.append(
            f"| {f['file']} | {_fmt(a.get('corridor_length_m'), 0)} | "
            f"{' / '.join(_fmt(v, 0) for v in sw)} | {_fmt(a.get('gps_duration_s'), 1)} | "
            f"{_fmt(a.get('platform_speed_m_s'), 1)} | {_fmt(a.get('point_rate_pts_s'))} | "
            f"{_band(prof, 0, 10)} | {_band(prof, 40, 50)} |"
        )
    t = result.get("survey_totals") or {}
    if t:
        lines += [
            "",
            "## 9. Survey totals and processing budget (estimates)",
            "",
            f"* Files: {t['files_total']} ({t['files_usable']} usable); LAZ "
            f"{t['laz_bytes_total'] / 2**30:.2f} GiB; header points "
            f"{_fmt(t['header_points_total'])}; valid points {_fmt(t['valid_points_total'])}",
            f"* Corridor length ≈ {_fmt(t['corridor_length_m_total'], 0)} m; road candidate "
            f"{t['road_candidate_area_m2_total'] / 1e4:.1f} ha; road corridor (+buffer) "
            f"{t['road_corridor_area_m2_total'] / 1e4:.1f} ha",
            "",
            "| Tiling option | Tiles touching corridor |",
            "|---|---:|",
        ]
        lines += [f"| {k} | {_fmt(v)} |" for k, v in t["tiles_touching_corridor"].items()]
        lines += [
            "",
            f"| GSD m | Corridor Mpx | RAM GB @ {t['raster_bytes_per_px_assumed']} B/px |"
            " Bbox Gpx if rasterised naively |",
            "|---:|---:|---:|---:|",
        ]
        lines += [
            f"| {g} | {_fmt(v['corridor_megapixels'], 1)} | "
            f"{_fmt(v['in_memory_GB_at_18_bytes_per_px'])} | "
            f"{_fmt(v['bbox_gigapixels_if_rasterised_naively'])} |"
            for g, v in t["raster_budget"].items()
        ]
    lines += [
        "",
        "## 10. Figures",
        "",
        "All in `outputs/reports/lidar_previews/`:",
        "",
        "* `intensity_histograms.png`, `road_density_hist.png`, `all_density_hist.png`, "
        "`regional_road_intensity.png`",
        "* `<file>_overview_1m.png` — per-file 1 m maps (intensity, density, "
        "single-return fraction, road candidate)",
        "* `<window>_gsdNNNmm.png` + `_imax.tif` / `_count.tif` — previews; GeoTIFFs carry "
        "the exact affine transform (no CRS, none is declared in the source)",
        "* `<window>_normalization.png` — raw vs global vs local normalisation",
        "",
    ]
    return "\n".join(lines)
